# --- アップロード ---
# **サイズの上限は置かない。** 上限を置くと、超えたときに利用者が手で
# 分割・圧縮する作業が復活してしまう（それを無くすのが今回の目的）。
# 代わりに「ディスクの空きが足りないときだけ、アップロードを始める前に断る」。
# 旧 MAX_FILE_SIZE_MB = 500 / ALLOWED_EXTENSIONS（拡張子の白リスト）は撤廃した。
# 対応形式の判定は拡張子ではなく ffmpeg 自身が行う（audio_pipeline.probe_media）。

# ブラウザが1回に送る断片の大きさ（MB）。ファイル全体はメモリに載らない。
# **サーバーが1断片として受け取る上限はこの値の2倍（既定 32MB）。**
# ちょうどで打ち切らないのは、送ってくる側の1断片が設定値と一致しない場合
# （最後の断片・設定変更後の古いタブ・API を直接叩く利用者）に、正しい送信を
# 413 で弾かないため。したがって同時アップロード1本あたりのメモリは
# 最大 32MB で止まる（app.upload_chunk の limit を参照）。
UPLOAD_CHUNK_MB = 16

# ディスクの空き検査で、常に空けておく余裕（GB）。
# 保存先のドライブをぎりぎりまで埋めないため。
DISK_RESERVE_GB = 1.0

# 取り出し後の WAV の大きさの見積もり（16kHz/モノラル/16bit = 約115MB/時間）。
# 空き容量の必要量の計算に使う。
WAV_MB_PER_HOUR = 115

# 音声の長さが分からない状態でアップロードが始まるときに、
# 変換後の音声のぶんとして見込んでおく最低量（GB）。約8.7時間分の WAV に相当。
WAV_UNKNOWN_FLOOR_GB = 1.0

# 中断されたまま放置されたアップロードの断片を消すまでの時間（時間）。
# **この値は「ディスクの空きの予約を手放すまでの時間」も兼ねる。**
# 受付（/upload/init）は「これから書き込む予定の量」を予約し、空きの判定から
# 差し引く（同時アップロードで空きを二重取りしないため）。送信が失敗したときは
# 画面が予約を手放すが、ブラウザやPCごと落ちて手放せなかった場合は、
# この時間が過ぎて断片が片付くまで予約が残る。
# つまり「ドライブは空いているのに『空き容量が足りません』と断られる」ときは、
# 進行中・放置中のアップロードが押さえている可能性がある（断り文に内訳が出る）。
UPLOAD_PART_TTL_HOURS = 24

# ffmpeg の「止まった」判定（秒）。
# **全体の時間制限ではない。** 何時間かかってもよいが、この秒数のあいだ
# 進捗がまったく進まなければ異常とみなして中止し、ジョブを失敗にする。
# 旧実装は 300 秒の全体タイムアウトで、超えると黙って前処理なしで続行していた。
FFMPEG_STALL_SEC = 600

